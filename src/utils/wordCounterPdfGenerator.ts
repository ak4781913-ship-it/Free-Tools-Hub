import jsPDF from 'jspdf';
import { recordPrintDocument } from './printHistoryTracking';

export interface WordCounterStats {
  words: number;
  charactersWithSpaces: number;
  charactersWithoutSpaces: number;
  sentences: number;
  paragraphs: number;
  readingTimeMinutes: number;
  speakingTimeMinutes: number;
  avgWordLength?: number;
  avgSentenceLength?: number;
}

export interface KeywordItem {
  word: string;
  count: number;
  percentage: number;
}

export function generateWordCounterPDF(
  text: string,
  stats: WordCounterStats,
  topKeywords: KeywordItem[] = []
): jsPDF {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = 210;
  const pageHeight = 297;
  const marginX = 16;
  const contentWidth = pageWidth - marginX * 2; // 178mm

  // Colors
  const primaryDark = [15, 23, 42]; // Slate 900
  const indigoBrand = [79, 70, 229]; // Indigo 600
  const slateText = [51, 65, 85]; // Slate 700
  const slateMuted = [100, 116, 139]; // Slate 500

  // 1. Header Banner
  doc.setFillColor(primaryDark[0], primaryDark[1], primaryDark[2]);
  doc.roundedRect(marginX, 14, contentWidth, 22, 2, 2, 'F');

  // Decorative Accent
  doc.setFillColor(indigoBrand[0], indigoBrand[1], indigoBrand[2]);
  doc.rect(marginX, 34.5, contentWidth, 1.5, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('TEXT METRICS & READABILITY AUDIT REPORT', marginX + 6, 23);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(203, 213, 225);
  const dateStr = new Date().toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
  });
  doc.text(`Generated by FreeTools Hub  •  ${dateStr}`, marginX + 6, 30);

  let currentY = 44;

  // 2. Executive KPI Cards (Grid of 4 top stats)
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.setTextColor(primaryDark[0], primaryDark[1], primaryDark[2]);
  doc.text('KEY QUANTITATIVE METRICS', marginX, currentY);
  currentY += 4;

  const cardWidth = (contentWidth - 6) / 4;
  const cardHeight = 20;

  const kpis = [
    { label: 'Total Words', value: stats.words.toLocaleString(), color: indigoBrand },
    { label: 'Characters', value: stats.charactersWithSpaces.toLocaleString(), color: [16, 185, 129] },
    { label: 'Sentences', value: stats.sentences.toLocaleString(), color: [59, 130, 246] },
    { label: 'Paragraphs', value: stats.paragraphs.toLocaleString(), color: [139, 92, 246] },
  ];

  kpis.forEach((kpi, idx) => {
    const cardX = marginX + idx * (cardWidth + 2);
    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(cardX, currentY, cardWidth, cardHeight, 1.5, 1.5, 'FD');

    // Label
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(slateMuted[0], slateMuted[1], slateMuted[2]);
    doc.text(kpi.label, cardX + 3.5, currentY + 6);

    // Value
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(kpi.color[0], kpi.color[1], kpi.color[2]);
    doc.text(kpi.value, cardX + 3.5, currentY + 15);
  });

  currentY += cardHeight + 8;

  // 3. Detailed Statistics Table
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.setTextColor(primaryDark[0], primaryDark[1], primaryDark[2]);
  doc.text('READING TIME & STRUCTURAL DENSITY', marginX, currentY);
  currentY += 4;

  const details = [
    ['Characters (Without Spaces)', stats.charactersWithoutSpaces.toLocaleString(), 'Estimated Reading Time (200 wpm)', `${stats.readingTimeMinutes} min`],
    ['Average Word Length', stats.words > 0 ? `${(stats.charactersWithoutSpaces / stats.words).toFixed(1)} chars` : '0', 'Estimated Speaking Time (130 wpm)', `${stats.speakingTimeMinutes} min`],
    ['Average Sentence Length', stats.sentences > 0 ? `${(stats.words / stats.sentences).toFixed(1)} words` : '0', 'Reading Ease Level', stats.words > 10 ? 'Standard / Conversational' : 'Brief'],
  ];

  const colWidth = contentWidth / 2;
  const rowHeight = 7;

  details.forEach((row, rIdx) => {
    const rowY = currentY + rIdx * rowHeight;
    doc.setFillColor(rIdx % 2 === 0 ? 255 : 248, rIdx % 2 === 0 ? 255 : 250, rIdx % 2 === 0 ? 255 : 252);
    doc.rect(marginX, rowY, contentWidth, rowHeight, 'F');
    doc.setDrawColor(226, 232, 240);
    doc.line(marginX, rowY + rowHeight, marginX + contentWidth, rowY + rowHeight);

    // Col 1 label & val
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.5);
    doc.setTextColor(slateMuted[0], slateMuted[1], slateMuted[2]);
    doc.text(row[0], marginX + 3, rowY + 5);

    doc.setFont('helvetica', 'bold');
    doc.setTextColor(slateText[0], slateText[1], slateText[2]);
    doc.text(row[1], marginX + colWidth - 8, rowY + 5, { align: 'right' });

    // Col 2 label & val
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(slateMuted[0], slateMuted[1], slateMuted[2]);
    doc.text(row[2], marginX + colWidth + 3, rowY + 5);

    doc.setFont('helvetica', 'bold');
    doc.setTextColor(slateText[0], slateText[1], slateText[2]);
    doc.text(row[3], marginX + contentWidth - 4, rowY + 5, { align: 'right' });
  });

  currentY += details.length * rowHeight + 10;

  // 4. Top Keyword Densities (if available)
  if (topKeywords.length > 0) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10.5);
    doc.setTextColor(primaryDark[0], primaryDark[1], primaryDark[2]);
    doc.text('FREQUENT KEYWORD DENSITY', marginX, currentY);
    currentY += 4;

    // Header row
    doc.setFillColor(241, 245, 249);
    doc.rect(marginX, currentY, contentWidth, 6, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(slateMuted[0], slateMuted[1], slateMuted[2]);
    doc.text('#', marginX + 4, currentY + 4.2);
    doc.text('KEYWORD / TERM', marginX + 16, currentY + 4.2);
    doc.text('FREQUENCY', marginX + 90, currentY + 4.2);
    doc.text('DENSITY (%)', marginX + 140, currentY + 4.2);
    currentY += 6;

    topKeywords.slice(0, 8).forEach((item, kIdx) => {
      const kY = currentY + kIdx * 6;
      doc.setFillColor(kIdx % 2 === 0 ? 255 : 248, kIdx % 2 === 0 ? 255 : 250, kIdx % 2 === 0 ? 255 : 252);
      doc.rect(marginX, kY, contentWidth, 6, 'F');

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(slateMuted[0], slateMuted[1], slateMuted[2]);
      doc.text(String(kIdx + 1), marginX + 4, kY + 4.2);

      doc.setFont('helvetica', 'bold');
      doc.setTextColor(slateText[0], slateText[1], slateText[2]);
      doc.text(item.word, marginX + 16, kY + 4.2);

      doc.setFont('helvetica', 'normal');
      doc.text(`${item.count} occurrences`, marginX + 90, kY + 4.2);
      doc.text(`${item.percentage.toFixed(1)}%`, marginX + 140, kY + 4.2);
    });

    currentY += Math.min(topKeywords.length, 8) * 6 + 10;
  }

  // 5. Analyzed Text Sample
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.setTextColor(primaryDark[0], primaryDark[1], primaryDark[2]);
  doc.text('ANALYZED TEXT EXCERPT', marginX, currentY);
  currentY += 4;

  const sampleSnippet = text.trim() ? text.slice(0, 750) + (text.length > 750 ? ' ... [truncated]' : '') : '(No text provided)';
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(slateText[0], slateText[1], slateText[2]);

  const textLines = doc.splitTextToSize(sampleSnippet, contentWidth - 8);
  const boxHeight = Math.min(textLines.length * 4.2 + 6, 70);

  doc.setFillColor(248, 250, 252);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(marginX, currentY, contentWidth, boxHeight, 1.5, 1.5, 'FD');
  doc.text(textLines.slice(0, 14), marginX + 4, currentY + 5);

  // Footer
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.3);
  doc.line(marginX, pageHeight - 12, marginX + contentWidth, pageHeight - 12);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text('FreeTools Hub  •  Word Counter & Text Analysis Report', marginX, pageHeight - 7);
  doc.text('Page 1 of 1', marginX + contentWidth - 18, pageHeight - 7);

  return doc;
}

export function downloadWordCounterPDF(
  text: string,
  stats: WordCounterStats,
  topKeywords: KeywordItem[] = []
): string {
  const doc = generateWordCounterPDF(text, stats, topKeywords);
  const fileName = `Text_Analysis_Report_${new Date().toISOString().slice(0, 10)}.pdf`;
  doc.save(fileName);

  recordPrintDocument('word-counter', `Text Analysis Report (${stats.words} words)`, {
    toolName: 'Word & Character Counter',
    format: 'Executive PDF Report',
    summary: `${stats.words} words • ${stats.charactersWithSpaces} characters • ${stats.readingTimeMinutes} min read`,
  });

  return fileName;
}
